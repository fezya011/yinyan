    public function search(?string $query = null, int $limit = 20): array
    {
        if (empty($query)) {
            return array_slice($this->cities, 0, $limit);
        }

        $filtered = array_filter($this->cities, function ($city) use ($query) {
            return mb_stripos($city, $query) !== false;
        });

        // Сортируем по релевантности
        usort($filtered, function ($a, $b) use ($query) {
            $aStarts = mb_stripos($a, $query) === 0;
            $bStarts = mb_stripos($b, $query) === 0;
            if ($aStarts && !$bStarts) return -1;
            if (!$aStarts && $bStarts) return 1;
            return strcasecmp($a, $b);
        });

        return array_slice(array_values($filtered), 0, $limit);
    }
